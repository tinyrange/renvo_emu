//! Deterministic generation engine for the checked-in C conformance corpus.
#![allow(
    clippy::cast_possible_truncation,
    clippy::many_single_char_names,
    clippy::too_many_lines
)]

use std::collections::HashSet;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

const CASE_COUNT: usize = 1_000;
const KERNEL_COUNT: usize = 40;
const SCENARIOS_PER_KERNEL: usize = CASE_COUNT / KERNEL_COUNT;

const GCC_TORTURE: &str =
    "https://gcc.gnu.org/onlinedocs/gccint/Testsuites.html#index-gcc_002ec_002dtorture";
const LLVM_TEST_SUITE: &str = "https://llvm.org/docs/TestingGuide.html#test-suite-overview";
const EMBENCH: &str = "https://github.com/embench/embench-iot";
const CSMITH: &str = "https://github.com/csmith-project/csmith";

mod kernels;
use kernels::{digest, kernel};

pub(crate) fn generate(output: &Path) -> Result<(), Box<dyn std::error::Error>> {
    let cases = output.join("cases");
    fs::create_dir_all(&cases)?;

    let mut manifest =
        String::from("case_id\tname\tcategory\tsignature\texpected_hex\tinspiration\n");
    let mut signatures = HashSet::with_capacity(CASE_COUNT);
    for id in 0..CASE_COUNT {
        let generated = generate_case(id);
        assert!(
            signatures.insert(generated.signature.clone()),
            "duplicate structural signature: {}",
            generated.signature
        );
        fs::write(cases.join(format!("case_{id:04}.c")), generated.source)?;
        writeln!(
            manifest,
            "case_{id:04}\t{}\t{}\t{}\t0x{:08x}\t{}",
            generated.name,
            generated.category,
            generated.signature,
            generated.expected,
            generated.inspiration
        )?;
    }
    fs::write(output.join("manifest.tsv"), manifest)?;
    println!(
        "generated {CASE_COUNT} cases from {KERNEL_COUNT} kernels in {}",
        cases.display()
    );
    Ok(())
}

struct GeneratedCase {
    name: String,
    category: &'static str,
    signature: String,
    expected: u32,
    inspiration: &'static str,
    source: String,
}

struct Kernel {
    slug: &'static str,
    category: &'static str,
    expected: u32,
    inspiration: &'static str,
    helpers: String,
    body: String,
}

fn generate_case(id: usize) -> GeneratedCase {
    let kernel_id = id / SCENARIOS_PER_KERNEL;
    let scenario = id % SCENARIOS_PER_KERNEL;
    let mut rng = Rng::new(0x7265_6e76_6f00_0000 | u64::try_from(id).unwrap());
    let mut input = [0_u32; 16];
    for value in &mut input {
        *value = rng.next_u32();
    }
    apply_boundary_scenario(&mut input, scenario);

    let kernel = kernel(kernel_id, scenario, &input);
    let synthesis = synthesize(id, kernel.expected, &input);
    let name = format!("{}--{}", kernel.slug, synthesis.short_name);
    let values = input
        .iter()
        .map(|value| format!("0x{value:08x}u"))
        .collect::<Vec<_>>()
        .join(", ");
    let source = format!(
        "/* Generated by renvo-casegen. Do not edit by hand.\n\
         * case: case_{id:04}\n\
         * name: {name}\n\
         * category: {category}\n\
         * structural signature: {signature}\n\
         * inspiration: {inspiration}\n\
         * kernel expected: 0x{kernel_expected:08x}\n\
         * expected: 0x{expected:08x}\n\
         * Contract: freestanding ISO C unsigned arithmetic; no undefined behavior.\n\
         */\n\
         typedef unsigned int u32;\n\
         typedef unsigned short u16;\n\
         typedef unsigned char u8;\n\
         \n\
         static volatile u32 input[16] = {{ {values} }};\n\
         {helpers}\n\
         __attribute__((noinline)) static u32 renvo_kernel(void)\n\
         {{\n\
         {kernel_body}\n\
         }}\n\
         \n\
         #ifdef RENVO_KERNEL_ONLY\n\
         __attribute__((noinline, used)) u32 renvo_case(void)\n\
         {{\n\
         \x20   return renvo_kernel();\n\
         }}\n\
         #else\n\
         __attribute__((noinline, used)) u32 renvo_case(void)\n\
         {{\n\
         {synthesized_body}\n\
         }}\n\
         #endif\n",
        category = kernel.category,
        inspiration = kernel.inspiration,
        signature = synthesis.signature,
        expected = synthesis.expected,
        kernel_expected = kernel.expected,
        helpers = kernel.helpers,
        kernel_body = indent(&kernel.body, 4),
        synthesized_body = indent(&synthesis.body, 4),
    );
    GeneratedCase {
        name,
        category: kernel.category,
        signature: synthesis.signature,
        expected: synthesis.expected,
        inspiration: kernel.inspiration,
        source,
    }
}

struct Synthesis {
    short_name: String,
    signature: String,
    expected: u32,
    body: String,
}

const OP_NAMES: [&str; 20] = [
    "add-carry",
    "sub-borrow",
    "rotate-mix",
    "multiply-low",
    "divide-rem",
    "mask-merge",
    "compare-select",
    "byte-pack",
    "halfword-swap",
    "array-scatter",
    "counted-loop",
    "switch-phi",
    "short-circuit",
    "popcount-loop",
    "reverse-loop",
    "gray-decode",
    "minmax-clamp",
    "endian-swap",
    "carry-chain",
    "horner-loop",
];

fn synthesize(id: usize, kernel_expected: u32, input: &[u32; 16]) -> Synthesis {
    let mut rng = Rng::new(0x6469_7374_696c_0000 ^ u64::try_from(id).unwrap());
    let mut registers = [
        kernel_expected,
        input[(id + 1) & 15],
        input[(id + 5) & 15],
        input[(id + 9) & 15],
        input[(id + 13) & 15],
        (id as u32).wrapping_mul(0x9e37_79b9),
    ];
    let mut memory = [0_u32; 8];
    for (index, value) in memory.iter_mut().enumerate() {
        *value = input[index] ^ (id as u32).rotate_left(index as u32);
    }

    // The first three base-20 digits encode the case ID. Consequently no two
    // cases can have the same structural operation sequence.
    let mut remaining = id;
    let mut operations = Vec::with_capacity(12);
    for _ in 0..3 {
        operations.push(remaining % OP_NAMES.len());
        remaining /= OP_NAMES.len();
    }
    for _ in 3..12 {
        operations.push((rng.next_u32() as usize) % OP_NAMES.len());
    }

    let signature = operations
        .iter()
        .map(|operation| OP_NAMES[*operation])
        .collect::<Vec<_>>()
        .join(",");
    let short_name = format!(
        "{}-{}-{}-{:03x}",
        OP_NAMES[operations[0]], OP_NAMES[operations[1]], OP_NAMES[operations[2]], id
    );

    let mut statements = String::from(
        "u32 r[6];\n\
         u32 memory[8];\n\
         r[0] = renvo_kernel();\n",
    );
    for index in 1..5 {
        writeln!(
            statements,
            "r[{index}] = input[{}];",
            (id + [0, 1, 5, 9, 13][index]) & 15
        )
        .unwrap();
    }
    writeln!(
        statements,
        "r[5] = 0x{:08x}u;",
        (id as u32).wrapping_mul(0x9e37_79b9)
    )
    .unwrap();
    for index in 0_u32..8 {
        writeln!(
            statements,
            "memory[{index}] = input[{index}] ^ 0x{:08x}u;",
            (id as u32).rotate_left(index)
        )
        .unwrap();
    }

    for (step, operation) in operations.iter().copied().enumerate() {
        let destination = (rng.next_u32() as usize) % registers.len();
        let left = (rng.next_u32() as usize) % registers.len();
        let right = (rng.next_u32() as usize) % registers.len();
        emit_operation(
            operation,
            step,
            destination,
            left,
            right,
            &mut registers,
            &mut memory,
            &mut statements,
        );
        let checkpoint = digest(&registers) ^ digest(&memory).rotate_left(11);
        writeln!(
            statements,
            "/* checkpoint {}: {:08x}; registers: {} */\n\
             #if defined(RENVO_STOP_AFTER) && RENVO_STOP_AFTER == {}\n\
             #if defined(RENVO_RETURN_REGISTER)\n\
             return r[RENVO_RETURN_REGISTER];\n\
             #elif defined(RENVO_RETURN_MEMORY)\n\
             return memory[RENVO_RETURN_MEMORY];\n\
             #else\n\
             u32 checkpoint_result{step} = 0x9e3779b9u;\n\
             for (u32 checkpoint_i{step} = 0u; checkpoint_i{step} < 6u; ++checkpoint_i{step}) checkpoint_result{step} = (checkpoint_result{step} << 5u) ^ (checkpoint_result{step} >> 2u) ^ r[checkpoint_i{step}];\n\
             #if defined(RENVO_RETURN_REGISTER_DIGEST)\n\
             return checkpoint_result{step};\n\
             #endif\n\
             u32 checkpoint_memory{step} = 0x9e3779b9u;\n\
             for (u32 checkpoint_i{step} = 0u; checkpoint_i{step} < 8u; ++checkpoint_i{step}) checkpoint_memory{step} = (checkpoint_memory{step} << 5u) ^ (checkpoint_memory{step} >> 2u) ^ memory[checkpoint_i{step}];\n\
             #if defined(RENVO_RETURN_MEMORY_DIGEST)\n\
             return checkpoint_memory{step};\n\
             #endif\n\
             return checkpoint_result{step} ^ (checkpoint_memory{step} << 11u | checkpoint_memory{step} >> 21u);\n\
             #endif\n\
             #endif",
            step + 1,
            checkpoint,
            registers
                .iter()
                .map(|value| format!("{value:08x}"))
                .collect::<Vec<_>>()
                .join(" "),
            step + 1
        )
        .unwrap();
    }

    let mut expected = digest(&registers);
    expected ^= digest(&memory).rotate_left(11);
    writeln!(
        statements,
        "/* reference final registers: {} */",
        registers
            .iter()
            .map(|value| format!("{value:08x}"))
            .collect::<Vec<_>>()
            .join(" ")
    )
    .unwrap();
    writeln!(
        statements,
        "/* reference final memory: {} */",
        memory
            .iter()
            .map(|value| format!("{value:08x}"))
            .collect::<Vec<_>>()
            .join(" ")
    )
    .unwrap();
    statements.push_str(
        "u32 result = 0x9e3779b9u;\n\
         for (u32 i = 0u; i < 6u; ++i) result = (result << 5u) ^ (result >> 2u) ^ r[i];\n\
         u32 memory_result = 0x9e3779b9u;\n\
         for (u32 i = 0u; i < 8u; ++i) memory_result = (memory_result << 5u) ^ (memory_result >> 2u) ^ memory[i];\n\
         return result ^ ((memory_result << 11u) | (memory_result >> 21u));",
    );

    Synthesis {
        short_name,
        signature,
        expected,
        body: statements,
    }
}

#[allow(clippy::too_many_arguments)]
fn emit_operation(
    operation: usize,
    step: usize,
    destination: usize,
    left: usize,
    right: usize,
    registers: &mut [u32; 6],
    memory: &mut [u32; 8],
    output: &mut String,
) {
    let a = registers[left];
    let b = registers[right];
    match operation {
        0 => {
            let sum = a.wrapping_add(b);
            registers[destination] = sum ^ u32::from(sum < a);
            writeln!(
                output,
                "u32 sum{step} = r[{left}] + r[{right}]; r[{destination}] = sum{step} ^ (sum{step} < r[{left}]);"
            )
            .unwrap();
        }
        1 => {
            let difference = a.wrapping_sub(b);
            registers[destination] = difference ^ u32::from(a < b);
            writeln!(
                output,
                "u32 diff{step} = r[{left}] - r[{right}]; r[{destination}] = diff{step} ^ (r[{left}] < r[{right}]);"
            )
            .unwrap();
        }
        2 => {
            let shift = b & 31;
            registers[destination] = a.rotate_left(shift) ^ b.rotate_right((shift + 7) & 31);
            writeln!(
                output,
                "u32 shift{step} = r[{right}] & 31u; r[{destination}] = (shift{step} == 0u ? r[{left}] : (r[{left}] << shift{step}) | (r[{left}] >> (32u - shift{step}))) ^ (((shift{step} + 7u) & 31u) == 0u ? r[{right}] : (r[{right}] >> ((shift{step} + 7u) & 31u)) | (r[{right}] << (32u - ((shift{step} + 7u) & 31u))));"
            )
            .unwrap();
        }
        3 => {
            registers[destination] = a.wrapping_mul(b | 1).wrapping_add(0x9e37_79b9);
            writeln!(
                output,
                "r[{destination}] = r[{left}] * (r[{right}] | 1u) + 0x9e3779b9u;"
            )
            .unwrap();
        }
        4 => {
            let divisor = (b & 0xffff) | 1;
            registers[destination] = (a / divisor) ^ (a % divisor).rotate_left(9);
            writeln!(
                output,
                "u32 divisor{step} = (r[{right}] & 0xffffu) | 1u; u32 rem{step} = r[{left}] % divisor{step}; r[{destination}] = (r[{left}] / divisor{step}) ^ (rem{step} << 9u | rem{step} >> 23u);"
            )
            .unwrap();
        }
        5 => {
            let mask = a.rotate_left((step as u32 + 3) & 31);
            registers[destination] = (a & mask) | (b & !mask);
            writeln!(
                output,
                "u32 mask{step} = (r[{left}] << {}u) | (r[{left}] >> {}u); r[{destination}] = (r[{left}] & mask{step}) | (r[{right}] & ~mask{step});",
                (step + 3) & 31,
                32 - ((step + 3) & 31)
            )
            .unwrap();
        }
        6 => {
            registers[destination] = if a < b {
                a.wrapping_add(0x1020_4081)
            } else {
                b.wrapping_sub(0x0102_0408)
            };
            writeln!(
                output,
                "r[{destination}] = (r[{left}] < r[{right}]) ? r[{left}] + 0x10204081u : r[{right}] - 0x01020408u;"
            )
            .unwrap();
        }
        7 => {
            registers[destination] =
                (a & 0xff) | ((b & 0xff) << 8) | ((a >> 8 & 0xff) << 16) | ((b >> 8 & 0xff) << 24);
            writeln!(
                output,
                "r[{destination}] = (r[{left}] & 0xffu) | ((r[{right}] & 0xffu) << 8u) | (((r[{left}] >> 8u) & 0xffu) << 16u) | (((r[{right}] >> 8u) & 0xffu) << 24u);"
            )
            .unwrap();
        }
        8 => {
            registers[destination] = a.rotate_left(16) ^ (b & 0xffff_0000);
            writeln!(
                output,
                "r[{destination}] = (r[{left}] << 16u | r[{left}] >> 16u) ^ (r[{right}] & 0xffff0000u);"
            )
            .unwrap();
        }
        9 => {
            let index = (a & 7) as usize;
            memory[index] ^= b;
            registers[destination] = memory[index].rotate_left((step as u32 + 1) & 31);
            writeln!(
                output,
                "u32 index{step} = r[{left}] & 7u; memory[index{step}] ^= r[{right}]; r[{destination}] = (memory[index{step}] << {}u) | (memory[index{step}] >> {}u);",
                step + 1,
                31 - step
            )
            .unwrap();
        }
        10 => {
            let count = 3 + step as u32 % 5;
            let mut value = a;
            for i in 0..count {
                value = value.wrapping_add(b ^ i).rotate_left(3);
            }
            registers[destination] = value;
            writeln!(
                output,
                "u32 loop{step} = r[{left}]; for (u32 i{step} = 0u; i{step} < {count}u; ++i{step}) {{ loop{step} += r[{right}] ^ i{step}; loop{step} = loop{step} << 3u | loop{step} >> 29u; }} r[{destination}] = loop{step};"
            )
            .unwrap();
        }
        11 => {
            registers[destination] = match a & 3 {
                0 => b.wrapping_add(a),
                1 => b.wrapping_sub(a),
                2 => b ^ a.rotate_left(5),
                _ => b.wrapping_mul(3) ^ a,
            };
            writeln!(
                output,
                "switch (r[{left}] & 3u) {{ case 0u: r[{destination}] = r[{right}] + r[{left}]; break; case 1u: r[{destination}] = r[{right}] - r[{left}]; break; case 2u: r[{destination}] = r[{right}] ^ (r[{left}] << 5u | r[{left}] >> 27u); break; default: r[{destination}] = r[{right}] * 3u ^ r[{left}]; break; }}"
            )
            .unwrap();
        }
        12 => {
            let mut effects = a;
            if b & 1 != 0 && {
                effects = effects.wrapping_add(3);
                b & 2 != 0
            } {
                effects ^= 0x55aa_55aa;
            }
            registers[destination] = effects;
            writeln!(
                output,
                "u32 effects{step} = r[{left}]; if ((r[{right}] & 1u) != 0u && (effects{step} += 3u, (r[{right}] & 2u) != 0u)) effects{step} ^= 0x55aa55aau; r[{destination}] = effects{step};"
            )
            .unwrap();
        }
        13 => {
            registers[destination] = a.count_ones() ^ b;
            writeln!(
                output,
                "u32 bits{step} = r[{left}], count{step} = 0u; while (bits{step} != 0u) {{ bits{step} &= bits{step} - 1u; ++count{step}; }} r[{destination}] = count{step} ^ r[{right}];"
            )
            .unwrap();
        }
        14 => {
            registers[destination] = a.reverse_bits() ^ b;
            writeln!(
                output,
                "u32 source{step} = r[{left}], reversed{step} = 0u; for (u32 i{step} = 0u; i{step} < 32u; ++i{step}) {{ reversed{step} = (reversed{step} << 1u) | (source{step} & 1u); source{step} >>= 1u; }} r[{destination}] = reversed{step} ^ r[{right}];"
            )
            .unwrap();
        }
        15 => {
            let mut value = a ^ (a >> 1);
            value ^= value >> 1;
            value ^= value >> 2;
            value ^= value >> 4;
            value ^= value >> 8;
            value ^= value >> 16;
            registers[destination] = value ^ b;
            writeln!(
                output,
                "u32 gray{step} = r[{left}] ^ (r[{left}] >> 1u); gray{step} ^= gray{step} >> 1u; gray{step} ^= gray{step} >> 2u; gray{step} ^= gray{step} >> 4u; gray{step} ^= gray{step} >> 8u; gray{step} ^= gray{step} >> 16u; r[{destination}] = gray{step} ^ r[{right}];"
            )
            .unwrap();
        }
        16 => {
            let low = a.min(b);
            let high = a.max(b);
            registers[destination] = registers[destination].clamp(low, high) ^ low ^ high;
            writeln!(
                output,
                "u32 low{step} = r[{left}] < r[{right}] ? r[{left}] : r[{right}], high{step} = r[{left}] > r[{right}] ? r[{left}] : r[{right}]; u32 clamp{step} = r[{destination}] < low{step} ? low{step} : (r[{destination}] > high{step} ? high{step} : r[{destination}]); r[{destination}] = clamp{step} ^ low{step} ^ high{step};"
            )
            .unwrap();
        }
        17 => {
            registers[destination] = a.swap_bytes() ^ b.rotate_left(8);
            writeln!(
                output,
                "u32 endian{step} = ((r[{left}] & 0xffu) << 24u) | ((r[{left}] & 0xff00u) << 8u) | ((r[{left}] >> 8u) & 0xff00u) | (r[{left}] >> 24u); r[{destination}] = endian{step} ^ (r[{right}] << 8u | r[{right}] >> 24u);"
            )
            .unwrap();
        }
        18 => {
            let low = a.wrapping_add(b);
            let high = registers[destination]
                .wrapping_add(registers[(destination + 1) % 6])
                .wrapping_add(u32::from(low < a));
            registers[destination] = low ^ high;
            writeln!(
                output,
                "u32 low{step} = r[{left}] + r[{right}], carry{step} = low{step} < r[{left}]; u32 high{step} = r[{destination}] + r[{}] + carry{step}; r[{destination}] = low{step} ^ high{step};",
                (destination + 1) % 6
            )
            .unwrap();
        }
        19 => {
            let mut value = a;
            for coefficient in [3_u32, 5, 17, 257] {
                value = value.wrapping_mul(b | 1).wrapping_add(coefficient);
            }
            registers[destination] = value;
            writeln!(
                output,
                "u32 polynomial{step} = r[{left}]; const u32 coefficient{step}[4] = {{ 3u, 5u, 17u, 257u }}; for (u32 i{step} = 0u; i{step} < 4u; ++i{step}) polynomial{step} = polynomial{step} * (r[{right}] | 1u) + coefficient{step}[i{step}]; r[{destination}] = polynomial{step};"
            )
            .unwrap();
        }
        _ => unreachable!(),
    }
}

fn apply_boundary_scenario(input: &mut [u32; 16], scenario: usize) {
    const BOUNDARIES: [u32; 12] = [
        0,
        1,
        2,
        3,
        0x7f,
        0x80,
        0xff,
        0x100,
        0x7fff_ffff,
        0x8000_0000,
        0xffff_fffe,
        0xffff_ffff,
    ];
    input[scenario % input.len()] = BOUNDARIES[scenario % BOUNDARIES.len()];
    if scenario >= 12 {
        input[(scenario * 7) % input.len()] = BOUNDARIES[(scenario * 5) % BOUNDARIES.len()];
    }
}

fn bytes(input: &[u32; 16]) -> [u8; 16] {
    input.map(|value| value as u8)
}

fn indent(text: &str, spaces: usize) -> String {
    let prefix = " ".repeat(spaces);
    text.lines()
        .map(|line| format!("{prefix}{line}"))
        .collect::<Vec<_>>()
        .join("\n")
}

struct Rng(u64);

impl Rng {
    const fn new(seed: u64) -> Self {
        Self(seed)
    }

    fn next_u32(&mut self) -> u32 {
        let mut x = self.0;
        x ^= x << 13;
        x ^= x >> 7;
        x ^= x << 17;
        self.0 = x;
        (x ^ (x >> 32)) as u32
    }
}
